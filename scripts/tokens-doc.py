"""Writes docs/TOKENS.md from src/design-tokens/tokens.css. Run with: npm run tokens-doc"""
import re
from pathlib import Path

root_dir = Path(__file__).resolve().parent.parent
css = (root_dir / 'src/design-tokens/tokens.css').read_text()
block = css[css.index(':root {'):css.index('\n}\n')]
toks = dict(re.findall(r'^\s*(--[a-z0-9-]+):\s*([^;]+);', block, re.M))
# A trailing comment on the same line explains the token
comments = {k: c.strip() for k, c in re.findall(r'^[ \t]*(--[a-z0-9-]+):[^;\n]+;[ \t]*/\*[ \t]*(.*?)[ \t]*\*/', block, re.M)}


def resolve(value, depth=0):
    m = re.fullmatch(r'var\((--[a-z0-9-]+)\)', value.strip())
    return resolve(toks[m.group(1)], depth + 1) if m and depth < 5 else value


def luminance(hex_value):
    h = hex_value.lstrip('#')
    channels = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    channels = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * channels[0] + 0.7152 * channels[1] + 0.0722 * channels[2]


def contrast(a, b):
    x, y = luminance(a), luminance(b)
    return (max(x, y) + 0.05) / (min(x, y) + 0.05)


PARCHMENT, NAVY = toks['--parchment'], toks['--navy']


def rows(keys, with_contrast=True):
    lines = []
    for key in keys:
        value = toks[key]
        resolved = resolve(value)
        extra = ''
        if with_contrast:
            if re.fullmatch(r'#[0-9a-fA-F]{6}', resolved):
                extra = f' | {contrast(resolved, PARCHMENT):.1f} | {contrast(resolved, NAVY):.1f}'
            else:
                extra = ' | – | –'
        lines.append(f'| `{key}` | `{value}` | {comments.get(key, "")}{extra} |'.replace(' |  |', ' | |'))
    return '\n'.join(lines)


def starting(prefix):
    return [k for k in toks if k.startswith(prefix)]


palette = ['--navy', '--navy-light', '--ink', '--burgundy', '--burgundy-light', '--burgundy-dark', '--gold', '--gold-light',
           '--gold-dark', '--parchment', '--parchment-dark', '--ivory', '--charcoal', '--stone']
layout = ['--measure', '--container-sm', '--container-md', '--container-book', '--container-lg', '--gutter', '--section-y',
          '--page-top', '--header-height', '--header-height-slim', '--tap-target']
spacing_scale = [k for k in toks if re.match(r'--space-\d', k)]
spacing_roles = starting('--gap-') + starting('--inset-')

md = f"""# Design tokens

<!-- Generated by scripts/tokens-doc.py. Edit tokens.css, then run: npm run tokens-doc -->

All values live in [`src/design-tokens/tokens.css`](../src/design-tokens/tokens.css). This page is a readable summary. For swatches, type samples and live contrast checks, open [`tokens.html`](tokens.html) in a browser: it reads `tokens.css` directly, so it never goes stale.

## Rules

- Use tokens, never raw values.
- **Colour:** components use the `--color-*` roles. Palette names are for brand decoration only (gold rules, burgundy accents).
- **Headings** get `--font-display` globally; components set size and weight only.
- **Running text** is capped at `--measure`. Centred blocks use the `centered` mixin.
- **Spacing:** use the roles. `--gap-related` between things that belong together, `--gap-items` between items in a group, `--gap-groups` between groups; `--inset-*` for padding. A container's padding is at least its largest inner gap, and equal on all sides unless there's a reason.
- **Dark sections** include the `on-dark` mixin, which switches `--color-accent` and `--color-focus` to gold.

## Colour

### Palette

Contrast is the WCAG ratio against parchment and navy. Body text needs 4.5, large text 3.0.

| Token | Value | Note | On parchment | On navy |
|---|---|---|---|---|
{rows(palette)}

### Roles

| Token | Value | Note | On parchment | On navy |
|---|---|---|---|---|
{rows(starting('--color-'))}

## Type

| Token | Value | Note |
|---|---|---|
{rows(starting('--font-') + starting('--text-'), False)}

## Spacing

### Roles (use these)

| Token | Value | Note |
|---|---|---|
{rows(spacing_roles, False)}

### Scale

| Token | Value | Note |
|---|---|---|
{rows(spacing_scale, False)}

## Layout

| Token | Value | Note |
|---|---|---|
{rows(layout, False)}

## Layers

| Token | Value | Note |
|---|---|---|
{rows(starting('--z-'), False)}
"""
(root_dir / 'docs/TOKENS.md').write_text(md)
print('Wrote docs/TOKENS.md')
